// Marcadores ocultos usados para localizar o que o pr-sentinel já publicou.
const (
	// Marker identifica o comentário de resumo (atualizado a cada push).
	Marker       = "<!-- pr-sentinel -->"
	reviewMarker = "<!-- pr-sentinel:review -->"
	inlinePrefix = "<!-- pr-sentinel:inline:"
)

type labels struct {
	title, risk, summary, findings, missingTests, truncated, partial, suggestion, inlineNote, footer, failed, ignored, cfgWarn, noFindings string
	riskNames                                                                                                                              map[string]string
}

var (
	ptLabels = labels{
		title: "Revisão automática", risk: "Risco geral", summary: "Resumo", findings: "Achados",
		missingTests: "Testes que estão faltando", suggestion: "Sugestão",
		truncated:  "⚠️ O diff excedeu o limite configurado. Arquivos **não revisados**:",
		partial:    "Arquivos revisados **parcialmente** (hunks omitidos):",
		inlineNote: "%d de %d achados foram publicados como comentários inline no código.",
		footer:     "Gerado por pr-sentinel · modelo `%s` · commit `%s`",
		failed:     "⚠️ O pr-sentinel não conseguiu concluir a revisão deste PR (%s). O PR **não** foi bloqueado. Envie um novo commit para tentar novamente.",
		ignored:    "%d arquivo(s) ignorado(s) por filtros (lockfiles, gerados, binários, vendor ou globs configurados).",
		cfgWarn:    "⚠️ Configuração do repositório ignorada: %s",
		noFindings: "Nenhum problema encontrado nas mudanças revisadas.",
		riskNames:  map[string]string{"low": "🟢 baixo", "medium": "🟡 médio", "high": "🔴 alto"},
	}
	enLabels = labels{
		title: "Automated review", risk: "Overall risk", summary: "Summary", findings: "Findings",
		missingTests: "Missing tests", suggestion: "Suggestion",
		truncated:  "⚠️ The diff exceeded the configured limit. Files **not reviewed**:",
		partial:    "Files reviewed **partially** (hunks omitted):",
		inlineNote: "%d of %d findings were posted as inline comments on the code.",
		footer:     "Generated by pr-sentinel · model `%s` · commit `%s`",
		failed:     "⚠️ pr-sentinel could not complete the review of this PR (%s). The PR was **not** blocked. Push a new commit to try again.",
		ignored:    "%d file(s) ignored by filters (lockfiles, generated, binary, vendor or configured globs).",
		cfgWarn:    "⚠️ Repository configuration ignored: %s",
		noFindings: "No issues found in the reviewed changes.",
		riskNames:  map[string]string{"low": "🟢 low", "medium": "🟡 medium", "high": "🔴 high"},
	}
)

func labelsFor(lang string) labels {
	if strings.HasPrefix(strings.ToLower(lang), "pt") {
		return ptLabels
	}
	return enLabels
}

var severityIcon = map[config.Severity]string{
	config.SeverityInfo: "🔵", config.SeverityWarning: "🟡", config.SeverityCritical: "🔴",
}

// SummaryInput reúne tudo o que o comentário de resumo exibe.
type SummaryInput struct {
	Result        Result
	Others        []Finding // achados que não foram publicados inline
	Total         int       // total de achados após filtro de severidade
	Inline        int       // quantos já estão inline
	Omitted       []string
	Partial       []string
	IgnoredFiles  int
	ConfigWarning string
	Language      string
	Model         string
	HeadSHA       string
}

var (
	reMention = regexp.MustCompile(`@(\w)`)
	reHTML    = regexp.MustCompile(`(?i)<(/?)(img|script|iframe|style|a|svg|link|meta|form|input|object|embed|base)\b`)
)

// sanitize neutraliza saída do modelo antes de ir para um comentário público:
// impede marcadores ocultos forjados (que quebrariam a busca do comentário),
// menções que notificam pessoas, imagens remotas e tags HTML ativas.
func sanitize(s string) string {
	s = strings.ReplaceAll(s, "<!--", "&lt;!--")
	s = strings.ReplaceAll(s, "-->", "--&gt;")
	s = reHTML.ReplaceAllString(s, "&lt;$1$2")
	s = strings.ReplaceAll(s, "![", `!\[`)
	s = reMention.ReplaceAllString(s, "@​$1")
	return s
}

func quote(s string) string {
	return "> " + strings.ReplaceAll(strings.TrimSpace(s), "\n", "\n> ")
}

func shortSHA(s string) string {
	if len(s) > 7 {
		return s[:7]
	}
	return s
}

func location(f Finding) string {
	if f.Line > 0 {
		return fmt.Sprintf("`%s:%d`", f.File, f.Line)
	}
	return fmt.Sprintf("`%s`", f.File)
}

// RenderSummary gera o comentário de resumo (sempre começa com Marker).
func RenderSummary(in SummaryInput) string {
	l := labelsFor(in.Language)
	var b strings.Builder
	b.WriteString(Marker + "\n")
	fmt.Fprintf(&b, "## 🛡️ pr-sentinel — %s\n\n", l.title)
	fmt.Fprintf(&b, "**%s:** %s\n\n", l.risk, l.riskNames[in.Result.RiskLevel])

	if in.ConfigWarning != "" {
		fmt.Fprintf(&b, l.cfgWarn+"\n\n", sanitize(in.ConfigWarning))
	}
	if len(in.Omitted) > 0 {
		fmt.Fprintf(&b, "%s\n", l.truncated)
		for _, p := range in.Omitted {
			fmt.Fprintf(&b, "- `%s`\n", p)
		}
		b.WriteString("\n")
	}
	if len(in.Partial) > 0 {
		fmt.Fprintf(&b, "%s\n", l.partial)
		for _, p := range in.Partial {
			fmt.Fprintf(&b, "- `%s`\n", p)
		}
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "### %s\n\n%s\n\n", l.summary, sanitize(in.Result.Summary))

	fmt.Fprintf(&b, "### %s (%d)\n\n", l.findings, in.Total)
	if in.Total == 0 {
		b.WriteString(l.noFindings + "\n\n")
	}
	if in.Inline > 0 {
		fmt.Fprintf(&b, l.inlineNote+"\n\n", in.Inline, in.Total)
	}
	for _, f := range in.Others {
		fmt.Fprintf(&b, "- %s **%s · %s** %s — %s\n", severityIcon[f.Severity], f.Severity, f.Category, location(f), sanitize(f.Message))
		if f.Suggestion != "" {
			fmt.Fprintf(&b, "\n  %s\n\n", strings.ReplaceAll(quote("💡 "+l.suggestion+": "+sanitize(f.Suggestion)), "\n", "\n  "))
		}
	}
	if len(in.Others) > 0 {
		b.WriteString("\n")
	}

	if len(in.Result.MissingTests) > 0 {
		fmt.Fprintf(&b, "### %s\n\n", l.missingTests)
		for _, t := range in.Result.MissingTests {
			fmt.Fprintf(&b, "- %s\n", sanitize(t))
		}
		b.WriteString("\n")
	}

	if in.IgnoredFiles > 0 {
		fmt.Fprintf(&b, "<sub>"+l.ignored+"</sub>\n\n", in.IgnoredFiles)
	}
	fmt.Fprintf(&b, "<sub>"+l.footer+"</sub>\n", in.Model, shortSHA(in.HeadSHA))
	return b.String()
}

// RenderFailure gera o comentário publicado quando a revisão falha.
func RenderFailure(lang, reason string) string {
	return Marker + "\n" + fmt.Sprintf("## 🛡️ pr-sentinel\n\n"+labelsFor(lang).failed+"\n", reason)
}

// InlineID identifica um achado de forma estável entre pushes (não depende da
// linha, que muda quando o código se move).
func InlineID(f Finding) string {
	h := sha256.Sum256([]byte(f.File + "\x00" + string(f.Category) + "\x00" + f.Message))
	return hex.EncodeToString(h[:6])
}

// RenderInline gera o corpo de um comentário inline.
func RenderInline(f Finding, lang string) string {
	l := labelsFor(lang)
	var b strings.Builder
	fmt.Fprintf(&b, "%s%s -->\n", inlinePrefix, InlineID(f))
	fmt.Fprintf(&b, "**%s %s · %s**\n\n%s\n", severityIcon[f.Severity], f.Severity, f.Category, sanitize(f.Message))
	if f.Suggestion != "" {
		fmt.Fprintf(&b, "\n%s\n", quote("💡 "+l.suggestion+": "+sanitize(f.Suggestion)))
	}
	return b.String()
}

// RenderReviewBody é o corpo (obrigatório) da revisão que agrupa os inline.
func RenderReviewBody(lang string, n int) string {
	if strings.HasPrefix(strings.ToLower(lang), "pt") {
		return fmt.Sprintf("%s\n🛡️ pr-sentinel: %d comentário(s) inline.", reviewMarker, n)
	}
	return fmt.Sprintf("%s\n🛡️ pr-sentinel: %d inline comment(s).", reviewMarker, n)
}
