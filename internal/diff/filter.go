// Package diff filtra e trunca os arquivos alterados de um PR antes de enviá-los
// à IA, mantendo apenas o que vale a pena revisar dentro de um orçamento de bytes.
package diff

import (
	"path"
	"strings"
)

// File é um arquivo alterado em um PR, como devolvido pela API do GitHub.
// Patch vazio indica binário ou diff grande demais para a API.
type File struct {
	Path      string
	Status    string // added, modified, removed, renamed...
	Patch     string
	Additions int
	Deletions int
	// Partial é true quando hunks foram removidos por truncamento.
	Partial bool
}

// Skipped descreve um arquivo descartado e o motivo.
type Skipped struct {
	Path   string
	Reason string
}

// Motivos de descarte.
const (
	ReasonLockfile  = "lockfile"
	ReasonVendor    = "dependências (vendor/node_modules)"
	ReasonGenerated = "arquivo gerado"
	ReasonBinary    = "binário ou sem diff textual"
	ReasonRemoved   = "arquivo removido"
	ReasonIgnored   = "ignorado por configuração"
)

var lockfiles = map[string]bool{
	"package-lock.json": true, "yarn.lock": true, "pnpm-lock.yaml": true,
	"go.sum": true, "Cargo.lock": true, "poetry.lock": true, "Pipfile.lock": true,
	"composer.lock": true, "Gemfile.lock": true, "bun.lockb": true,
	"packages.lock.json": true, "gradle.lockfile": true,
}

var vendorDirs = []string{"vendor", "node_modules", "bower_components", "third_party"}

var generatedSuffixes = []string{
	".pb.go", "_generated.go", ".gen.go", "_gen.go", ".pb.cc", ".pb.h", "_pb2.py", "_pb2_grpc.py",
	".min.js", ".min.css", ".js.map", ".css.map", ".designer.cs", ".g.dart", ".freezed.dart",
}

var generatedMarkers = []string{"code generated", "@generated", "auto-generated", "autogenerated"}

var binaryExts = map[string]bool{
	".png": true, ".jpg": true, ".jpeg": true, ".gif": true, ".webp": true, ".ico": true, ".bmp": true,
	".pdf": true, ".zip": true, ".gz": true, ".tar": true, ".tgz": true, ".7z": true, ".jar": true,
	".exe": true, ".dll": true, ".so": true, ".dylib": true, ".bin": true, ".class": true, ".wasm": true,
	".woff": true, ".woff2": true, ".ttf": true, ".eot": true, ".otf": true,
	".mp3": true, ".mp4": true, ".mov": true, ".avi": true,
}

// Filter separa os arquivos que devem ser revisados dos descartados. ignore são
// globs adicionais (suporta "**"); a ordem de entrada é preservada.
func Filter(files []File, ignore []string) (kept []File, skipped []Skipped) {
	for _, f := range files {
		if reason := skipReason(f, ignore); reason != "" {
			skipped = append(skipped, Skipped{Path: f.Path, Reason: reason})
			continue
		}
		kept = append(kept, f)
	}
	return kept, skipped
}

func skipReason(f File, ignore []string) string {
	base := path.Base(f.Path)
	switch {
	case f.Status == "removed":
		return ReasonRemoved
	case lockfiles[base]:
		return ReasonLockfile
	case inVendor(f.Path):
		return ReasonVendor
	case binaryExts[strings.ToLower(path.Ext(base))] || f.Patch == "":
		return ReasonBinary
	case isGenerated(f):
		return ReasonGenerated
	}
	for _, g := range ignore {
		if Match(g, f.Path) {
			return ReasonIgnored
		}
	}
	return ""
}

func inVendor(p string) bool {
	for _, seg := range strings.Split(p, "/") {
		for _, d := range vendorDirs {
			if seg == d {
				return true
			}
		}
	}
	return false
}

func isGenerated(f File) bool {
	lower := strings.ToLower(f.Path)
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(lower, s) {
			return true
		}
	}
	// Marcadores costumam ficar no cabeçalho, que aparece no primeiro hunk de arquivos novos.
	head := f.Patch
	if len(head) > 2048 {
		head = head[:2048]
	}
	head = strings.ToLower(head)
	for _, m := range generatedMarkers {
		if strings.Contains(head, m) {
			return true
		}
	}
	return false
}

// Match informa se name casa com o glob. Suporta "*", "?", classes de
// caracteres (como path.Match) e "**" para qualquer número de diretórios.
// Padrões sem "/" casam também apenas com o nome do arquivo (ex.: "*.md").
func Match(pattern, name string) bool {
	pattern = strings.TrimPrefix(pattern, "./")
	name = strings.TrimPrefix(name, "./")
	if !strings.Contains(pattern, "/") {
		ok, _ := path.Match(pattern, path.Base(name))
		return ok
	}
	// "dir/" equivale a "dir/**".
	if strings.HasSuffix(pattern, "/") {
		pattern += "**"
	}
	return matchSegments(strings.Split(pattern, "/"), strings.Split(name, "/"))
}

func matchSegments(pat, name []string) bool {
	for len(pat) > 0 {
		if pat[0] == "**" {
			rest := pat[1:]
			if len(rest) == 0 {
				return true
			}
			for i := 0; i <= len(name); i++ {
				if matchSegments(rest, name[i:]) {
					return true
				}
			}
			return false
		}
		if len(name) == 0 {
			return false
		}
		if ok, err := path.Match(pat[0], name[0]); err != nil || !ok {
			return false
		}
		pat, name = pat[1:], name[1:]
	}
	return len(name) == 0
}
