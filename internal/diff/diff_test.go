func TestMatch(t *testing.T) {
	tests := []struct {
		pattern, name string
		want          bool
	}{
		{"*.md", "README.md", true},
		{"*.md", "docs/guide/intro.md", true},
		{"docs/**", "docs/a/b.txt", true},
		{"docs/**", "src/docs/a.txt", false},
		{"docs/", "docs/a.txt", true},
		{"**/*.snap", "a/b/c.snap", true},
		{"**/*.snap", "c.snap", true},
		{"src/*/x.go", "src/a/x.go", true},
		{"src/*/x.go", "src/a/b/x.go", false},
		{"./gen/**", "gen/x", true},
		{"a/**/z", "a/z", true},
		{"a/**/z", "a/b/c/z", true},
		{"a/[", "a/b", false}, // padrão inválido não casa
		{"Makefile", "build/Makefile", true},
	}
	for _, tt := range tests {
		t.Run(tt.pattern+"|"+tt.name, func(t *testing.T) {
			if got := Match(tt.pattern, tt.name); got != tt.want {
				t.Fatalf("Match(%q, %q) = %v", tt.pattern, tt.name, got)
			}
		})
	}
}

func TestFilter(t *testing.T) {
	p := "@@ -1 +1 @@\n-a\n+b\n"
	tests := []struct {
		name   string
		file   File
		ignore []string
		reason string
	}{
		{"código normal", File{Path: "main.go", Status: "modified", Patch: p}, nil, ""},
		{"go.sum", File{Path: "go.sum", Status: "modified", Patch: p}, nil, ReasonLockfile},
		{"lockfile em subpasta", File{Path: "web/package-lock.json", Status: "modified", Patch: p}, nil, ReasonLockfile},
		{"yarn.lock", File{Path: "yarn.lock", Status: "modified", Patch: p}, nil, ReasonLockfile},
		{"vendor", File{Path: "vendor/x/y.go", Status: "added", Patch: p}, nil, ReasonVendor},
		{"node_modules", File{Path: "a/node_modules/b.js", Status: "added", Patch: p}, nil, ReasonVendor},
		{"vendor não é prefixo", File{Path: "vendorized/y.go", Status: "added", Patch: p}, nil, ""},
		{"png", File{Path: "logo.PNG", Status: "added", Patch: p}, nil, ReasonBinary},
		{"sem patch", File{Path: "data.dat", Status: "added"}, nil, ReasonBinary},
		{"pb.go", File{Path: "api/x.pb.go", Status: "modified", Patch: p}, nil, ReasonGenerated},
		{"min.js", File{Path: "static/app.min.js", Status: "modified", Patch: p}, nil, ReasonGenerated},
		{"marcador no conteúdo", File{Path: "x.go", Status: "added", Patch: "@@ -0,0 +1 @@\n+// Code generated by foo. DO NOT EDIT.\n"}, nil, ReasonGenerated},
		{"removido", File{Path: "old.go", Status: "removed", Patch: p}, nil, ReasonRemoved},
		{"glob do usuário", File{Path: "docs/a.md", Status: "modified", Patch: p}, []string{"docs/**"}, ReasonIgnored},
		{"glob não casa", File{Path: "src/a.go", Status: "modified", Patch: p}, []string{"docs/**"}, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			kept, skipped := Filter([]File{tt.file}, tt.ignore)
			if tt.reason == "" {
				if len(kept) != 1 || len(skipped) != 0 {
					t.Fatalf("esperava manter, skipped=%v", skipped)
				}
				return
			}
			if len(kept) != 0 || len(skipped) != 1 || skipped[0].Reason != tt.reason {
				t.Fatalf("kept=%v skipped=%v, quer motivo %q", kept, skipped, tt.reason)
			}
		})
	}
}

func hunk(lines int) string {
	var b strings.Builder
	b.WriteString("@@ -1 +1 @@\n")
	for i := 0; i < lines; i++ {
		b.WriteString("+linha\n")
	}
	return b.String()
}

func TestSplitHunks(t *testing.T) {
	patch := hunk(2) + hunk(1) + hunk(3)
	hunks := splitHunks(patch)
	if len(hunks) != 3 {
		t.Fatalf("len = %d", len(hunks))
	}
	if strings.Join(hunks, "") != patch {
		t.Fatal("join deve reconstruir o patch")
	}
	if got := splitHunks(""); len(got) != 0 {
		t.Fatalf("vazio = %v", got)
	}
	if got := splitHunks("sem hunk\nlinha"); len(got) != 1 {
		t.Fatalf("sem @@ = %v", got)
	}
}

func TestTruncate(t *testing.T) {
	code := File{Path: "a.go", Status: "modified", Patch: hunk(10)}
	test := File{Path: "a_test.go", Status: "modified", Patch: hunk(10)}
	doc := File{Path: "README.md", Status: "modified", Patch: hunk(10)}
	multi := File{Path: "m.go", Status: "modified", Patch: hunk(5) + hunk(5) + hunk(5)}

	paths := func(fs []File) []string {
		var out []string
		for _, f := range fs {
			out = append(out, f.Path)
		}
		return out
	}

	t.Run("cabe tudo", func(t *testing.T) {
		r := Truncate([]File{doc, test, code}, 100_000)
		if r.Truncated() || len(r.Files) != 3 {
			t.Fatalf("%+v", r)
		}
		if !reflect.DeepEqual(paths(r.Files), []string{"README.md", "a_test.go", "a.go"}) {
			t.Fatalf("ordem original perdida: %v", paths(r.Files))
		}
	})

	t.Run("prioriza código sobre testes e docs", func(t *testing.T) {
		budget := size(code) + 5
		r := Truncate([]File{doc, test, code}, budget)
		if !reflect.DeepEqual(paths(r.Files), []string{"a.go"}) {
			t.Fatalf("files = %v", paths(r.Files))
		}
		if !reflect.DeepEqual(r.Omitted, []string{"a_test.go", "README.md"}) {
			t.Fatalf("omitted = %v", r.Omitted)
		}
	})

	t.Run("corta em fronteira de hunk", func(t *testing.T) {
		h := len(hunk(5))
		r := Truncate([]File{multi}, len(multi.Path)+2*h+3)
		if len(r.Files) != 1 || !r.Files[0].Partial || len(r.Partial) != 1 {
			t.Fatalf("%+v", r)
		}
		if got := r.Files[0].Patch; got != hunk(5)+hunk(5) {
			t.Fatalf("patch cortado errado: %q", got)
		}
		if r.Bytes > len(multi.Path)+2*h+3 {
			t.Fatalf("estourou orçamento: %d", r.Bytes)
		}
	})

	t.Run("hunk único que não cabe é omitido", func(t *testing.T) {
		r := Truncate([]File{code}, 5)
		if len(r.Files) != 0 || !reflect.DeepEqual(r.Omitted, []string{"a.go"}) {
			t.Fatalf("%+v", r)
		}
	})

	t.Run("arquivo menor ainda entra depois de um grande omitido", func(t *testing.T) {
		small := File{Path: "s.go", Status: "added", Patch: "@@ -0,0 +1 @@\n+x\n"}
		r := Truncate([]File{code, small}, size(small)+1)
		if !reflect.DeepEqual(paths(r.Files), []string{"s.go"}) {
			t.Fatalf("files = %v", paths(r.Files))
		}
	})

	t.Run("vazio", func(t *testing.T) {
		if r := Truncate(nil, 10); r.Truncated() || len(r.Files) != 0 {
			t.Fatalf("%+v", r)
		}
	})
}

func TestPriority(t *testing.T) {
	tests := []struct {
		path string
		want int
	}{
		{"internal/x.go", 0},
		{"internal/x_test.go", 1},
		{"web/app.spec.ts", 1},
		{"tests/foo.py", 1},
		{"README.md", 2},
		{"config/app.yaml", 2},
		{"docs/x.go", 2},
	}
	for _, tt := range tests {
		if got := priority(tt.path); got != tt.want {
			t.Errorf("priority(%q) = %d, quer %d", tt.path, got, tt.want)
		}
	}
}

func TestFormat(t *testing.T) {
	got := Format([]File{
		{Path: "a.go", Status: "modified", Additions: 1, Deletions: 2, Patch: "@@ -1 +1 @@\n-a\n+b"},
		{Path: "b.go", Status: "added", Patch: "@@ -0,0 +1 @@\n+x\n", Partial: true},
	})
	for _, want := range []string{"### a.go (modified, +1 -2)\n@@ -1 +1 @@\n-a\n+b\n\n", "### b.go (added, +0 -0)", "omitidos"} {
		if !strings.Contains(got, want) {
			t.Errorf("faltou %q em:\n%s", want, got)
		}
	}
}
